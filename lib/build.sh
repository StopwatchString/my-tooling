# lib/build.sh — layered build engine behind setup.sh.
#
# A layer is a directory laid out like this repo; every part is optional. The
# stack is [this repo] [each --layer DIR, in order] [host layer], lowest
# precedence first. Each layer's layer.sh declares targets (link, link_each,
# block, generate, json, step); a target combines its path from EVERY layer,
# so a layer only adds files and never needs to know what the others contain.
# Targets run as they are declared. See docs/integration-guide.md.
#
# Must stay compatible with bash 3.2 (macOS /bin/bash): no associative arrays,
# no mapfile, no `readlink -f`, no ${var,,}.

STAMP="$(date +%Y%m%d%H%M%S)"
MODE=install
changes=0
problems=0
warnings=0
LAYERS=()       # absolute layer roots, lowest precedence first
LAYER=""        # root of the layer whose layer.sh is being sourced
SKIPS=()        # --skip patterns (destinations or step names)
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
STATE_DIR="$CONFIG_HOME/dotfiles"
HOST_LAYER="${DOTFILES_HOST_LAYER:-$STATE_DIR/host}"
BUILD="$STATE_DIR/build"        # generated files and the record of what's managed
RECORD="$BUILD/managed"
GEN_MARK="dotfiles: generated by setup.sh; edit the layers and re-run setup, not this file"

build_usage() {
  cat <<EOF
Usage: $(basename "$0") [--layer DIR]... [--skip PATTERN]... [option]

Build this machine's configs from a stack of layers: this repo, then each
--layer DIR in the order given, then the host layer
($HOST_LAYER, if it exists). Later layers win. Each layer's
layer.sh declares targets; every target gathers its files from all layers.
See docs/integration-guide.md in $DOTFILES.

  (none)        Create or refresh everything. Files in the way are moved to
                <name>.backup.<timestamp>. Things managed by an earlier run
                that this stack no longer produces are removed. Safe to re-run.
  -n, --dry-run Print what would change without touching anything.
  -s, --status  Show the state of every target:
                  ok      up to date
                  absent  not set up yet
                  DIFF    exists but differs from what the layers produce
                  FILE    a real file is in the way (will be backed up)
                  OTHER   a symlink pointing somewhere else (will be replaced)
                  LEGACY  an old symlink into a layer (will be replaced)
                  stale   managed by an earlier run, not by this stack
                  todo    a setup step still needs to run
                  WARN    a later layer overrides an earlier layer's item
  -u, --uninstall
                Remove everything setup manages: links, generated files,
                managed blocks and the JSON keys it set. Host content outside
                the blocks, backups and what steps did are left in place.
  --layer DIR   Add a layer on top of the ones before it. Downstream repos
                pass themselves this way from their own setup.sh.
  --skip PATTERN
                Leave out targets whose destination or step name matches the
                shell pattern (e.g. "*/ghostty/*", "GNOME Terminal profile").
                "<layer name>:PATTERN" skips only that layer's targets, so a
                layer can replace a lower one's target at the same dest.
  -h, --help    Show this help.
EOF
}

# Print a status line; $HOME is shown as ~.
say() {
  local msg="$2" t='~'
  printf '  %-8s %s\n' "$1" "${msg//"$HOME"/$t}"
}
problem() { say "$1" "$2"; problems=$((problems + 1)); }
warn()    { say WARN "$1"; warnings=$((warnings + 1)); }
run()     { if [[ $MODE == dry-run ]]; then :; else "$@"; fi; }

# Single-quote a string for sh.
shq() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }

# Display name of a layer root.
layer_name() {
  if [[ $1 == "$HOST_LAYER" ]]; then echo host; else basename "$1"; fi
}

# Layer roots joined with ':' (exported to shells as $DOTFILES_LAYERS).
layers_joined() {
  local IFS=:
  echo "${LAYERS[*]}"
}

# Print the target of a symlink (one level), or nothing.
link_target() { [[ -L $1 ]] && readlink "$1" || true; }

# Like link_target, but relative targets are made absolute.
abs_target() {
  local t
  t="$(link_target "$1")"
  case $t in
    ""|/*) echo "$t" ;;
    *)     echo "$(cd "$(dirname "$1")" && pwd -P)/$t" ;;
  esac
}

# True if PATH lies inside one of the layers.
in_layer() {
  local l
  [[ -n $1 ]] || return 1
  for l in "${LAYERS[@]}"; do
    case $1 in "$l"|"$l"/*) return 0 ;; esac
  done
  return 1
}

# Record a managed destination so a later run can prune it (kind: link, gen,
# block:<style>, json).
record() { printf '%s\t%s\n' "$1" "$2" >> "$TMPD/record"; }

# claim <dest> <signature>: returns 1 if the target should not run because
# it's skipped or was already declared identically (two layers may declare
# the same target). A different declaration for the same dest is a problem.
claim() {
  local dest="$1" sig="$2" prev p lname
  lname="$(layer_name "$LAYER")"
  for p in ${SKIPS[@]+"${SKIPS[@]}"}; do
    # A pattern prefixed "<layer name>:" only skips that layer's targets, so
    # a layer can replace a lower one's target at the same dest.
    case $p in "$lname:"*) p="${p#"$lname:"}" ;; esac
    # shellcheck disable=SC2254
    case $dest in $p) say skip "$dest"; return 1 ;; esac
    case ${dest#step: } in $p) say skip "$dest"; return 1 ;; esac
  done
  prev="$(awk -F'\t' -v d="$dest" '$1 == d { print $2; exit }' "$TMPD/claims")"
  if [[ -n $prev ]]; then
    [[ $prev == "$sig" ]] ||
      problem CONFLICT "$dest declared twice: '$prev' and '$sig' ($(layer_name "$LAYER"))"
    return 1
  fi
  printf '%s\t%s\n' "$dest" "$sig" >> "$TMPD/claims"
}

# free_parents <dest>: an ancestor of dest that is a symlink into a layer is
# an old whole-directory link (e.g. ~/.config/nvim -> repo/nvim); writing
# through it would write into the repo. Removes it (install/uninstall) or
# reports it. Sets GONE=1 when dest should be treated as not existing yet.
free_parents() {
  local d="${1%/*}" t
  GONE=0
  while [[ -n $d && $d != / ]]; do
    if [[ -L $d ]]; then
      t="$(abs_target "$d")"
      if in_layer "$t"; then
        if [[ $MODE == status || $MODE == dry-run ]]; then
          GONE=1
          # Report each old link once; dry-run and status don't remove it.
          grep -qxF -e "$d" "$TMPD/legacy" && return 0
          echo "$d" >> "$TMPD/legacy"
        fi
        case $MODE in
          status)    say LEGACY "$d -> $t (old directory link)" ;;
          dry-run)   say unlink "$d (old directory link -> $t)"; changes=$((changes + 1)) ;;
          install|uninstall)
            rm "$d"; say unlink "$d (old directory link -> $t)"; changes=$((changes + 1)) ;;
        esac
        return 0
      fi
    fi
    d="${d%/*}"
  done
}

# ensure_dir <dir>: dir must be a real directory (not a link) for per-item links.
ensure_dir() {
  local dir="$1" t
  free_parents "$dir/."
  [[ $GONE == 1 ]] && return 0
  if [[ -L $dir ]]; then
    t="$(abs_target "$dir")"
    case $MODE in
      status)    say OTHER "$dir -> $t (should be a real directory)" ;;
      uninstall) ;;
      *)
        say backup "$dir -> $dir.backup.$STAMP (directory link to $t)"
        run mv "$dir" "$dir.backup.$STAMP"
        changes=$((changes + 1))
        ;;
    esac
  fi
}

# place_link <src> <dest>: make dest a symlink to src.
place_link() {
  local src="$1" dest="$2" current=""
  free_parents "$dest"
  [[ $GONE == 1 ]] || current="$(link_target "$dest")"

  case $MODE in
    status)
      if [[ $GONE == 1 ]]; then say absent "$dest"
      elif [[ $current == "$src" ]]; then say ok "$dest"
      elif [[ -n $current ]] && in_layer "$current"; then say LEGACY "$dest -> $current"
      elif [[ -n $current ]]; then say OTHER "$dest -> $current"
      elif [[ -e $dest ]]; then say FILE "$dest (not linked)"
      else say absent "$dest"
      fi
      ;;

    uninstall)
      if [[ -n $current ]] && in_layer "$current"; then
        rm "$dest"; say removed "$dest"; changes=$((changes + 1))
      fi
      ;;

    install|dry-run)
      [[ $current == "$src" ]] && return 0
      if [[ -n $current ]]; then
        say relink "$dest (was -> $current)"
        run rm "$dest"
      elif [[ -e $dest && $GONE != 1 ]]; then
        say backup "$dest -> $dest.backup.$STAMP"
        run mv "$dest" "$dest.backup.$STAMP"
      fi
      run mkdir -p "$(dirname "$dest")"
      run ln -s "$src" "$dest"
      say link "$dest -> $src"
      changes=$((changes + 1))
      ;;
  esac
}

# put_file <dest> <new content file> <label>: write content to dest if it
# differs (install), keeping dest's mode when it is already a regular file.
# The caller has handled links and backups.
put_file() {
  local dest="$1" new="$2" label="$3"
  say "$label" "$dest"
  changes=$((changes + 1))
  [[ $MODE == install ]] || return 0
  if [[ -L $dest ]]; then rm "$dest"; fi
  mkdir -p "$(dirname "$dest")"
  if [[ -f $dest ]]; then cat "$new" > "$dest"; else cp "$new" "$dest"; fi
}

